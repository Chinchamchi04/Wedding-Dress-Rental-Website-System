async function seedDresses() {
  try {
    console.log('Connecting to MongoDB...');
    await mongoose.connect(process.env.MONGO_URI);
    console.log('Connected to MongoDB successfully!');

    // 1. Ensure categories exist
    const categoryMap = {
      Ballgown: { name: 'Váy Cưới Công Chúa (Ballgown)', slug: 'ballgown' },
      Mermaid: { name: 'Váy Cưới Đuôi Cá (Mermaid)', slug: 'mermaid' },
      'A-Line': { name: 'Váy Cưới Chữ A (A-Line)', slug: 'a-line' },
      'Silk Gown': { name: 'Váy Cưới Lụa Tối Giản (Silk Gown)', slug: 'silk-gown' },
      Princess: { name: 'Váy Cưới Hoàng Gia (Princess)', slug: 'princess' },
      Traditional: { name: 'Áo Cưới Truyền Thống (Traditional)', slug: 'traditional' },
      Tuxedo: { name: 'Vest Cưới & Tuxedo (Tuxedo)', slug: 'tuxedo' },
    };

    const categoriesInDb = {};
    for (const [key, val] of Object.entries(categoryMap)) {
      let cat = await Category.findOne({ slug: val.slug });
      if (!cat) {
        cat = await Category.create({
          name: val.name,
          slug: val.slug,
          description: `Danh mục ${val.name} thương hiệu UniBridal Atelier`,
          isActive: true,
        });
      }
      categoriesInDb[key] = cat._id;
    }

    // 2. Clear all existing dresses in database
    console.log('Deleting all existing dresses in database...');
    const deleteResult = await Dress.deleteMany({});
    console.log(`Deleted ${deleteResult.deletedCount} old dresses.`);

    // 3. Create 50 new dresses
    const dressesToInsert = DRESS_DATA.map((item, index) => {
      const numStr = (index + 1).toString().padStart(2, '0');
      const code = `UB-${(index + 1).toString().padStart(3, '0')}`;
      const slug = item.name
        .toLowerCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/[đĐ]/g, 'd')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');

      const imagePath = `/assets/dresses/dress_${numStr}.jpg`;

      return {
        code,
        name: item.name,
        slug: `${slug}-${code.toLowerCase()}`,
        categoryId: categoriesInDb[item.silhouette] || categoriesInDb['Ballgown'],
        silhouette: item.silhouette,
        material: item.material,
        color: item.color,
        rentPrice: item.rentPrice,
        depositAmount: item.depositAmount,
        originalPrice: item.originalPrice,
        sizes: item.sizes,
        images: [imagePath],
        status: 'available',
        rentCount: Math.floor(Math.random() * 80) + 20,
        isFeatured: index < 8,
        collectionTag: item.collectionTag,
        rating: 4.8 + Math.round(Math.random() * 2) / 10,
        reviewCount: Math.floor(Math.random() * 40) + 12,
        description: item.description,
        highlights: [
          {
            icon: 'diamond',
            label: 'Chất Liệu Thượng Hạng',
            value: item.material.split('&')[0].trim(),
            sub: 'Độc quyền Atelier UniBridal',
          },
          {
            icon: 'sparkles',
            label: 'Đính Kết Thủ Công',
            value: 'Pha Lê & Chỉ Tơ Kim',
            sub: '100% chế tác tay tỉ mỉ',
          },
          {
            icon: 'shield',
            label: 'Bảo Quản Chuẩn Atelier',
            value: 'Hấp nhiệt & Tiệt trùng UV',
            sub: 'Đóng gói vali chuyên dụng',
          },
        ],
        colorOptions: [
          { name: item.color, hex: '#FDFBF7', border: '#E7DEC8' },
          { name: 'Trắng Kem Ivory', hex: '#F6EFEB', border: '#D8C3BE' },
        ],
        story: {
          collectionName: item.collectionTag,
          title: item.name,
          content: [
            `Mẫu thiết kế ${item.name} được lấy cảm hứng từ vẻ đẹp tinh tế của thời trang Haute Couture Paris kết hợp cùng kỹ thuật may đo tỉ mỉ của nghệ nhân UniBridal.`,
            `Với chất liệu ${item.material}, chiếc váy giúp tôn vinh hoàn hảo đường nét yêu kiều của nàng dâu trong từng khoảnh khắc bước lên lễ đường thiêng liêng.`,
          ],
          atelierImage: imagePath,
          stats: [
            { value: `${Math.floor(Math.random() * 200) + 180}h`, label: 'CHẾ TÁC THỦ CÔNG' },
            { value: '100%', label: 'CHẤT LIỆU CAO CẤP' },
            { value: `${item.sizes.length} Size`, label: 'SỐ LƯỢNG KÍCH CỠ' },
          ],
        },
      };
    });

    console.log(`Inserting 50 new wedding dresses into database...`);
    const inserted = await Dress.insertMany(dressesToInsert);
    console.log(`Successfully seeded ${inserted.length} dresses with UniBridal logo and unique sizes!`);

    await mongoose.disconnect();
    console.log('MongoDB disconnected cleanly.');
  } catch (err) {
    console.error('Error seeding dresses:', err);
    process.exit(1);
  }
}

seedDresses();

